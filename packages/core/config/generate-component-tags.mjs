/**
 * Generates `src/global/constants/tags.constant.ts` and `_component-names.scss` — the list of
 * every `ds-*` custom element tag, scraped from each component's `@Component({ tag: ... })`
 * decorator. Both files are gitignored (see `.gitignore`) and regenerated on demand.
 *
 * `src/global/initialize.ts` imports `tags.constant.ts` at the top level, so it must exist before
 * Stencil's TS transpile phase runs. The `watch-external` rollup plugin in `stencil.config.ts`
 * regenerates it on every rebuild, but that hook only fires during the later bundle phase — too
 * late for a fresh checkout where these gitignored files don't exist yet. `scripts/build-core.mjs`
 * calls this function once before invoking Stencil to cover that case.
 *
 * Stencil bundles `lazy`, `hydrate app`, and `custom elements` concurrently, and each one's
 * `buildStart` fires this same `watch-external` hook — so this can be invoked multiple times in
 * parallel within a single process. Concurrent `writeFile`s to the same path can interleave and
 * leave a truncated file on disk for anything reading it mid-build (e.g. the global SCSS that
 * imports `_component-names.scss`), so in-flight calls share one promise and writes land via
 * write-to-temp-then-rename, which is atomic on POSIX and Windows.
 */
import fg from 'fast-glob'
import { mkdir, readFile, rename, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

async function writeFileAtomic(path, contents) {
  const tmpPath = `${path}.${process.pid}.${Date.now()}.tmp`
  await writeFile(tmpPath, contents)
  await rename(tmpPath, path)
}

let inFlight = null

export function generateComponentTags(coreRoot) {
  if (!inFlight) {
    inFlight = generateComponentTagsUncached(coreRoot).finally(() => {
      inFlight = null
    })
  }
  return inFlight
}

async function generateComponentTagsUncached(coreRoot) {
  // Use cwd + relative pattern to avoid Windows path separator issues with fast-glob
  const componentFiles = await fg('src/components/**/*.tsx', {
    cwd: coreRoot,
    ignore: ['**/*.data.tsx', '**/field.util.tsx', '**/*.interfaces.tsx', '**/index.tsx'],
  })
  const allTags = (
    await Promise.all(
      componentFiles.map(async f => {
        const src = await readFile(resolve(coreRoot, f), 'utf-8')
        const m = src.match(/tag:\s*['"`]([^'"`]+)['"`]/)
        return m ? m[1] : null
      }),
    )
  )
    .filter(t => !!t)
    .sort()

  const constantsDir = resolve(coreRoot, 'src/global/constants')
  await mkdir(constantsDir, { recursive: true })
  await writeFileAtomic(
    resolve(constantsDir, 'tags.constant.ts'),
    `// This file is auto-generated by stencil.config.ts - do not edit manually\n\nexport const tags: string[] = ${JSON.stringify(allTags, null, 2)}\n`,
  )
  await writeFileAtomic(
    resolve(constantsDir, '_component-names.scss'),
    `// This file is auto-generated by stencil.config.ts - do not edit manually\n\n$component-names: ${allTags.map(t => `'${t}'`).join(', ')};\n`,
  )

  return allTags
}
